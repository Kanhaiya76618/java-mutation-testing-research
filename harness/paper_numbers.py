"""
harness/paper_numbers.py

Writes numbers and tables for the paper as LaTeX files under paper/generated/, so the
paper never contains a result that was typed in by hand: paper/main.tex only \\input{}s
these files, and the analysis scripts regenerate them from the measured data.
"""

from __future__ import annotations
import re
from pathlib import Path
from typing import Dict, Iterable

GENERATED_DIR = Path(__file__).resolve().parent.parent / "paper" / "generated"


def _header(source: str) -> str:
    return f"% Generated by {source} from the measured data. Do not edit by hand.\n"


def write_macros(name: str, macros: Dict[str, str], source: str) -> Path:
    """Writes \\newcommand definitions. Macro names must be letters only (a LaTeX rule)."""
    lines = [_header(source)]
    for macro, value in macros.items():
        if not re.fullmatch(r"[A-Za-z]+", macro):
            raise ValueError(f"LaTeX macro names may only contain letters: {macro}")
        lines.append(f"\\newcommand{{\\{macro}}}{{{value}}}\n")
    return _write(name, "".join(lines))


def write_lines(name: str, lines: Iterable[str], source: str) -> Path:
    """Writes raw LaTeX lines (e.g. the rows of a tabular)."""
    return _write(name, _header(source) + "\n".join(lines) + "\n")


def _write(name: str, text: str) -> Path:
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    path = GENERATED_DIR / name
    path.write_text(text, encoding="utf-8")
    return path


def tex_escape(text: str) -> str:
    """Escapes the LaTeX special characters that appear in class and operator names."""
    return text.replace("\\", r"\textbackslash{}").replace("_", r"\_").replace("&", r"\&").replace("%", r"\%").replace("#", r"\#")
